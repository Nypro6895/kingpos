export function translateVietnamese(text: string, enabled: boolean) {
  if (!enabled) return text;
  const trimmed = text.trim().replace(/\s+/g, " ");
  const translated = VIETNAMESE_UI[trimmed];
  if (translated) return text.replace(text.trim(), translated);
  for (const template of templates) {
    const match = template.pattern.exec(trimmed);
    if (!match) continue;
    let value = template.value;
    template.slots.forEach((slot, index) => { value = value.replaceAll(slot, match[index + 1]); });
    return text.replace(text.trim(), value);
  }
  if (/\d/.test(trimmed)) return text.replace(/\b(?:January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Oct|Nov|Dec|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday|Mon|Tue|Wed|Thu|Fri|Sat|Sun)\b/g, word => calendarWords[word]);
  return text;
}
