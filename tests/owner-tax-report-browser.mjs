import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { chromium } from "playwright-core";

const base = process.env.OWNER_TAX_QA_URL;
assert.ok(base && /^http:\/\/(?:localhost|127\.0\.0\.1):\d+$/.test(base), "Use this task's explicit loopback Next server.");
const out = "artifacts/owner-tax-readonly-20261114/browser";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const checks = [], errors = [], writes = [], reads = [], timings = [];
const context = await browser.newContext();
const page = await context.newPage();
const observe = target => {
  target.on("pageerror", error => errors.push(error.message));
  target.on("request", request => {
    const path = new URL(request.url()).pathname;
    if (path.startsWith("/__nextjs")) return;
    if (!["GET", "HEAD", "OPTIONS"].includes(request.method())) writes.push(`${request.method()} ${path}`);
    if (path.startsWith("/api/tax/") || path === "/api/app-local/read") reads.push(path);
  });
};
observe(page);
const report = page.locator("[data-owner-tax-report]");
const row = (target, employee) => target.locator(`[data-tax-line='00000000-0000-4000-8000-${String(40 + employee).padStart(12, "0")}']`);
const detail = (target, employee) => target.locator(`[data-tax-expanded='00000000-0000-4000-8000-${String(40 + employee).padStart(12, "0")}']`);
const figures = target => target.locator("[data-tax-line]").evaluateAll(rows => rows.map(row => ({ id: row.getAttribute("data-tax-line"), figures: [...row.querySelectorAll("[data-tax-figure]")].map(cell => [cell.getAttribute("data-tax-figure"), cell.textContent]) })).sort((left, right) => left.id.localeCompare(right.id)));
const afterPaint = target => target.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
try {
  await page.goto(`${base}/tax/qa/owner-report`);
  await report.waitFor();
  assert.equal(new URL(page.url()).pathname, "/payroll/tax-company");
  await page.setViewportSize({ width: 1440, height: 1050 });
  assert.equal(await report.locator("form,input[type=file],[contenteditable=true]").count(), 0);
  assert.equal(await report.getByRole("button", { name: /upload|replace|save|pay|send|edit/i }).count(), 0);
  assert.equal(await report.locator("[data-tax-line]").count(), 6);
  assert.equal(await report.locator("[data-tax-expanded]").count(), 0, "Collapsed detail is not rendered upfront");
  await page.screenshot({ path: `${out}/owner-tax-1440-compact.png`, fullPage: true });
  checks.push("Real owner route renders six published employees with view-only controls and no upfront detail rows");

  const anna = row(page, 0);
  assert.equal(await anna.locator("[data-tax-figure=check_wage]").innerText(), "$1,000.00");
  assert.equal(await anna.locator("[data-tax-figure=check_net]").innerText(), "$950.00");
  assert.equal(await anna.locator("[data-tax-figure=cash_wage]").innerText(), "$300.00");
  assert.equal(await anna.locator("[data-tax-figure=tip]").innerText(), "$150.00");
  const requestsBefore = reads.length;
  const started = performance.now();
  await anna.getByRole("button", { name: "Expand details for Anna Nguyen", exact: true }).click();
  await afterPaint(page);
  timings.push({ action: "expand-one-six-employee-fixture", durationMs: Math.round(performance.now() - started) });
  const annaDetail = detail(page, 0);
  assert.equal(await annaDetail.locator("[data-tax-component]").count(), 4);
  const check = annaDetail.locator("[data-tax-component=check_wage]");
  assert.deepEqual(await check.locator("td").allTextContents(), ["$1,000.00", "Yes", "20%", "$200.00", "$800.00", "$1,000.00", "$200.00", "$800.00", "$0.00", "$0.00", "$0.00"]);
  const untaxedTip = annaDetail.locator("[data-tax-component=tip]");
  assert.deepEqual((await untaxedTip.locator("td").allTextContents()).slice(0, 5), ["$150.00", "No", "—", "$0.00", "$150.00"]);
  assert.deepEqual((await annaDetail.locator("[data-tax-component=cash_wage] td").allTextContents()).slice(0, 5), ["$300.00", "No", "—", "$0.00", "$300.00"]);
  await anna.locator("[data-tax-figure=check_net] button").click();
  assert.match(await report.getByLabel("Selected tax figure", { exact: true }).innerText(), /Anna Nguyen.*Check after withholding.*\$950\.00/s);
  await report.getByRole("tab", { name: "Check / Cash details", exact: true }).click();
  assert.equal(await report.getByRole("tabpanel", { name: "Check / Cash details", exact: true }).locator("[data-tax-breakdown]").count(), 6);
  await report.getByRole("tab", { name: "Reported figures", exact: true }).click();
  await report.getByRole("tab", { name: "Reported figures", exact: true }).press("ArrowRight");
  assert.equal(await report.getByRole("tab", { name: "Check / Cash details", exact: true }).getAttribute("aria-selected"), "true");
  await report.getByRole("tab", { name: "Check / Cash details", exact: true }).press("ArrowLeft");
  assert.equal(reads.length, requestsBefore, "Expand, inspect and sheet switching require no extra data reads");
  checks.push("Shared cash and tip remain visible with Apply tax No; Check wages 20% yields Check $950 including untaxed Tip $150, without extra reads");

  await row(page, 1).getByRole("button", { name: "Expand details for Brian Tran", exact: true }).click();
  const hiddenCash = detail(page, 1).locator("[data-tax-component=cash_wage]");
  assert.equal(await hiddenCash.getAttribute("data-shared"), "false");
  assert.ok((await hiddenCash.locator("td").allTextContents()).every(value => value === "—"));
  assert.equal(await row(page, 1).locator("[data-tax-figure=gross]").innerText(), "—");
  assert.equal(await row(page, 1).locator("[data-tax-figure=check_net]").innerText(), "$640.00");
  await row(page, 3).getByRole("button", { name: "Expand details for Michael Pham", exact: true }).click();
  assert.match(await detail(page, 3).innerText(), /Historical component detail unavailable/);
  assert.equal(await row(page, 3).locator("[data-tax-figure=reported_wage]").innerText(), "$900.00");
  assert.equal(await row(page, 3).locator("[data-tax-figure=gross]").innerText(), "$900.00");
  checks.push("Hidden components remain dashes without inferable totals; legacy headline figures stay usable with explicit unavailable detail");

  const ownerFigures = await figures(page);
  const professionalContext = await browser.newContext();
  await professionalContext.addCookies(await context.cookies());
  await professionalContext.addCookies([{ name: "reylumi-tax-qa-mode", value: "tax", url: base }]);
  const professional = await professionalContext.newPage(); observe(professional);
  await professional.goto(`${base}/tax/qa`);
  await professional.locator("[data-tax-figures-sheet]").waitFor();
  assert.deepEqual(ownerFigures, await figures(professional));
  await professional.getByLabel("Payroll period", { exact: true }).selectOption("00000000-0000-4000-8000-000000000030");
  await row(professional, 0).getByRole("button", { name: "View paystub", exact: true }).click();
  await professional.getByRole("dialog").waitFor();
  await professional.getByRole("button", { name: "Close", exact: true }).click();
  await row(professional, 3).getByRole("button", { name: "Upload needed", exact: true }).click();
  await professional.getByRole("dialog").waitFor();
  await professional.getByRole("button", { name: "Close", exact: true }).click();
  await professionalContext.close();
  checks.push("All owner/professional numeric cells match for the same period; professional paystub view/upload dialogs remain available");

  for (const width of [320, 390, 820, 1440]) {
    await page.setViewportSize({ width, height: 1050 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow at ${width}`);
    await report.getByText("Visible columns", { exact: true }).click();
    const cashOption = report.getByRole("checkbox", { name: "Cash net", exact: true });
    const menuBox = await cashOption.locator("..").locator("..").boundingBox();
    assert.ok(menuBox.x >= 0 && menuBox.x + menuBox.width <= width, `Column menu within viewport at ${width}`);
    await cashOption.uncheck();
    assert.equal(await report.locator("[data-tax-figure=cash_net]").count(), 0);
    await cashOption.check();
    await report.getByText("Visible columns", { exact: true }).click();
    await report.getByRole("button", { name: /Collapse all|Expand all/, exact: true }).click();
    const grid = report.getByRole("region", { name: "Tax figures spreadsheet", exact: true });
    const geometry = await grid.evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth, bodyWidth: document.documentElement.scrollWidth, viewport: innerWidth }));
    assert.ok(geometry.width <= width, `Local sheet scroll width ${width}`);
    assert.ok(geometry.scrollWidth >= geometry.width);
    await grid.evaluate(element => { element.scrollLeft = 450; });
    await afterPaint(page);
    const pinned = await row(page, 0).locator("td").first().boundingBox();
    const gridBox = await grid.boundingBox();
    assert.ok(pinned.x >= gridBox.x && pinned.x < gridBox.x + 50, `Pinned employee at ${width}`);
    await grid.evaluate(element => { element.scrollLeft = 0; });
    await page.evaluate(() => window.scrollTo(0, 0));
    await afterPaint(page);
    await page.screenshot({ path: `${out}/owner-tax-${width}.png`, fullPage: true });
    await page.getByLabel("Find tax report employee", { exact: true }).fill("Anna Thi");
    assert.equal(await report.locator("[data-tax-line]").count(), 1);
    await page.getByLabel("Find tax report employee", { exact: true }).fill("no-person-matches");
    await page.getByRole("heading", { name: "No matching employees", exact: true }).waitFor();
    await page.getByLabel("Find tax report employee", { exact: true }).fill("");
    checks.push(`No page overflow, contained horizontal sheet with pinned employee, search and empty state at ${width}px`);
  }
  await page.getByLabel("Tax reporting period", { exact: true }).selectOption("summary");
  assert.equal(await report.locator("option[value='00000000-0000-4000-8000-000000000031']").count(), 0);
  assert.equal(await row(page, 0).locator("[data-tax-figure=check_wage]").innerText(), "$2,000.00");
  await row(page, 2).getByRole("button", { name: "Expand details for Sophia Le", exact: true }).click();
  assert.equal((await detail(page, 2).locator("[data-tax-component=check_wage] td").allTextContents())[2], "Mixed rates");
  await page.goto(`${base}/payroll/tax-company?month=2024-10`);
  await page.getByRole("heading", { name: "No reporting figures for this period", exact: true }).waitFor();
  await page.getByRole("button", { name: "Clear date range", exact: true }).click();
  assert.equal(await report.locator("[data-tax-line]").count(), 6);
  checks.push("Latest revisions are counted once; summaries preserve mixed rates; missing requested periods stay empty with date-range recovery");
  assert.deepEqual(errors, []);
  assert.deepEqual(writes, []);
  checks.push("Owner interactions and professional read-only dialog opening caused no mutation requests or runtime errors");
  writeFileSync(`${out}/result.json`, JSON.stringify({ passed: true, base, checks, errors, writes, timings }, null, 2));
  console.log(JSON.stringify({ passed: true, checks: checks.length, errors, writes, timings, screenshots: out }));
} finally {
  await browser.close();
}
