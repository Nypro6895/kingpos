import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const owner='00000000-0000-4000-8000-000000000001', staff='00000000-0000-4000-8000-000000000002', other='00000000-0000-4000-8000-000000000003';
test('salon language consent, durable invitations, entitlement changes and access isolation', async () => {
 const db=new PGlite();
 try {
  await db.exec(`create role authenticated;create role anon;create role service_role;
   create table locations(id uuid primary key,status text,name text);
   create table users(id uuid primary key,language text default 'vi');
   create table staff(salon_id uuid,account_user_id uuid,is_active boolean);
   create function current_public_user_id() returns uuid language sql as $$select nullif(current_setting('test.user',true),'')::uuid$$;
   create function lifecycle_user_is_salon_owner(salon uuid,actor uuid,pending boolean) returns boolean language sql as $$select salon=actor$$;
   create function platform_admin_has_permission(permission text) returns boolean language sql as $$select false$$;
   insert into users(id) values('${owner}'),('${staff}'),('${other}');
   insert into locations values('${owner}','active','Salon B'),('${other}','active','Salon C');
   insert into staff values('${owner}','${staff}',true),('${other}','${staff}',true);`);
  await db.exec(fs.readFileSync('supabase/migrations/202610080006_vietnamese_market_plugin.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/20261110180000_salon_language_choices.sql','utf8'));
  const login=actor=>db.exec(`reset role;select set_config('test.user','${actor}',false);set role authenticated;`);
  const state=(salon=owner)=>db.query('select salon_language_state($1) s',[salon]).then(r=>r.rows[0].s);
  const choose=(code,activation=null,salon=owner)=>db.query('select salon_language_choose($1,$2,$3) s',[salon,code,activation]).then(r=>r.rows[0].s);
  await login(owner);
  await db.query('select vietnamese_plugin_set($1,true,true,false)',[owner]);
  assert.equal((await state()).effective,'en','package activation must not change owner language');
  await choose('vi');
  await db.query('select vietnamese_plugin_set($1,true,false,false)',[owner]);
  await db.exec(`reset role;insert into staff values('${owner}','${owner}',true);`);
  await login(owner);
  const staffMode=()=>db.query('select salon_language_state($1,true) s',[owner]).then(r=>r.rows[0].s);
  assert.equal((await staffMode()).effective,'en','staff workspace must honor staff grant even for an owner');
  await assert.rejects(db.query('select salon_language_choose($1,$2,null,true)',[owner,'vi']),/no longer available/);
  await db.query('select vietnamese_plugin_set($1,true,true,false)',[owner]);
  assert.equal((await state()).effective,'vi','staff access changes must not reset owner preference');
  assert.equal((await staffMode()).effective,'vi','explicit personal choice is preserved across eligible roles in the same salon');
  await choose('en');
  await login(staff);
  let first=await state();
  await assert.rejects(db.query('select salon_language_state($1,false)',[owner]),/Salon access/,'staff cannot claim management context');
  assert.equal(first.effective,'en','legacy users.language=vi is not consent');
  assert.equal(first.notices.length,1);assert.equal(first.notices[0].seen,false);
  assert.equal((await state()).notices.length,1,'deduplicated across app opens');
  const activation=first.offers[0].activation;
  await db.query('select salon_language_notice_seen($1,$2,$3)',[owner,'vi',activation]);
  assert.equal((await state()).notices[0].seen,true);
  assert.equal((await state()).effective,'en','later only acknowledges, never changes preference');
  assert.equal((await choose('vi',activation)).effective,'vi');
  const chosenRevision=BigInt((await state()).choiceRevision);
  assert.equal((await state()).effective,'vi','durable across requests');
  assert.equal((await state(other)).effective,'en','preference isolated per salon');
  await login(owner);assert.equal((await state()).effective,'en','preference isolated per user');
  await login(staff);
  assert.equal((await choose('en')).effective,'en','English always selectable');
  assert.ok(BigInt((await state()).choiceRevision)>chosenRevision,'each explicit choice advances its durable version');
  await assert.rejects(choose('fr'),/no longer available/);
  await assert.rejects(db.exec('select * from salon_language_choices'),/permission denied/);
  await assert.rejects(db.exec('update salon_language_notices set seen_at=null'),/permission denied/);
  await choose('vi');
  await login(owner);await db.query('select vietnamese_plugin_set($1,true,false,false)',[owner]);
  await login(staff);assert.equal((await state()).effective,'en');assert.deepEqual((await state()).offers,[]);
  await assert.rejects(choose('vi',activation),/no longer available/);
  await login(owner);await db.query('select vietnamese_plugin_set($1,true,true,false)',[owner]);
  await login(staff);const reactivated=await state();
  assert.equal(reactivated.effective,'en','re-enabling staff does not silently restore language');
  assert.notEqual(reactivated.offers[0].activation,activation);assert.equal(reactivated.notices[0].seen,false);
  await assert.rejects(choose('vi',activation),/no longer available/);
  await choose('vi',reactivated.offers[0].activation);
  await db.exec('reset role;update vietnamese_plugin_subscriptions set trial_ends_at=now()-interval \'1 day\';');
  await login(staff);assert.equal((await state()).effective,'en','expiry fallback');
  assert.equal((await state()).unavailable,true);await assert.rejects(choose('vi'),/no longer available/);
  await db.exec("reset role;update vietnamese_plugin_subscriptions set paid_until=now()+interval '1 month';");
  await login(staff);assert.equal((await state()).effective,'en','renewal after expiry needs fresh consent');
  await db.exec(`reset role;update staff set is_active=false where account_user_id='${staff}';`);
  await login(staff);await assert.rejects(state(),/Salon access/);await assert.rejects(choose('en'),/Salon access/);
  await login(other);await assert.rejects(state(),/Salon access/);
  await db.exec(`reset role;update staff set is_active=false where account_user_id='${owner}';`);
  await login(owner);await assert.rejects(staffMode(),/Salon access/,'owner status does not restore a revoked staff role');
  assert.equal((await state()).effective,'en','owner management entitlement remains separate');
  await db.exec('reset role;set role anon;');await assert.rejects(state(),/permission denied/);
 } finally {await db.close();}
});
