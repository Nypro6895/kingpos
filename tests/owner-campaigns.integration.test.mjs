import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import { PGlite } from "@electric-sql/pglite";

const owner = "00000000-0000-0000-0000-000000000001";
const stranger = "00000000-0000-0000-0000-000000000002";
const salon = "10000000-0000-0000-0000-000000000001";
const post = "20000000-0000-0000-0000-000000000001";
const campaign = "30000000-0000-0000-0000-000000000001";
const area = { country:"United States",state:"Illinois",city:"Chicago",zipcode:"",neighborhood:"" };
const visitor = "a".repeat(64);

test("owner campaign lifecycle, payment gate, targeting, caps and prompt deduplication", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create table users(id uuid primary key);
      create table accounts(id uuid primary key,status text);insert into accounts values('${salon}','active');
      create table locations(id uuid primary key,status text,account_id uuid);
      create table salon_settings(salon_id uuid,public_discovery_enabled boolean);insert into salon_settings values('${salon}',true);
      create table beauty_profiles(id uuid,visibility text);
      create table bookings(id uuid primary key,customer_user_id uuid,source_reference_id uuid,source_reference_type text,status text,confirmation_status text);
      create table salon_profile_looks(id uuid primary key,salon_id uuid,title text,caption text,status text,author_user_id uuid,safety_hold boolean default false,deleted_at timestamptz);
      create table salon_profile_updates(like salon_profile_looks including all);
      create table salon_profile_look_saves(id uuid primary key,user_id uuid,look_id uuid);
      create table account_post_saves(id uuid primary key,user_id uuid,source_type text,source_id uuid);
      create table salon_profile_comments(id uuid primary key,author_user_id uuid,look_id uuid,update_id uuid,beauty_post_id uuid,status text,is_salon_reply boolean);
      create table salon_profile_booking_requests(id uuid primary key,customer_user_id uuid,look_id uuid,status text);
      create table beauty_posts(like salon_profile_looks including all); alter table beauty_posts add column visibility text; alter table beauty_posts add column moderation_status text;
      create function lifecycle_user_is_salon_owner(uuid,uuid,boolean) returns boolean language sql as $$ select ($1='${salon}'::uuid and $2='${owner}'::uuid) or ($1='10000000-0000-0000-0000-000000000002'::uuid and $2='${stranger}'::uuid) $$;
      create function post_safety_table(text) returns text language sql as $$ select case $1 when 'beauty_post' then 'beauty_posts' when 'salon_profile_look' then 'salon_profile_looks' when 'salon_profile_update' then 'salon_profile_updates' end $$;
      insert into users values('${owner}'),('${stranger}'); insert into locations values('${salon}','active','${salon}');
    `);
    await db.exec(fs.readFileSync("supabase/migrations/202610080002_owner_campaigns.sql","utf8"));
    await db.exec(`insert into salon_profile_looks values('${post}','${salon}','Fresh look','New manicure','published','${owner}',false,null)`);
    const prompt = await db.query(`select owner_campaign_claim_prompt($1,$2) p`,[salon,owner]);
    assert.equal(prompt.rows[0].p.target.sourceId,post);
    assert.equal((await db.query(`select owner_campaign_claim_prompt($1,$2) p`,[salon,owner])).rows[0].p,null);
    const create = user => db.query(`select owner_campaign_create($1,$2,$3,'salon_profile_look',$4,'city','Chicago','United States','Illinois','Chicago',500,7) id`,[campaign,salon,user,post]);
    await assert.rejects(create(stranger),/Owner access/);
    assert.equal((await create(owner)).rows[0].id,campaign);
    assert.equal((await create(owner)).rows[0].id,campaign);
    assert.equal((await db.query(`select count(*)::int n from owner_campaigns`)).rows[0].n,1);
    await assert.rejects(db.query(`select owner_campaign_review($1,true)`,[campaign]),/Only paid/);
    const admit = (kind="view",location=area,nonce="40000000-0000-0000-0000-000000000001",viewer=null) => db.query(`select owner_campaign_admit($1,$2,$3,$4,$5,$6) ok`,[campaign,visitor,kind,location,viewer,nonce]);
    assert.equal((await admit()).rows[0].ok,false);
    await assert.rejects(db.query(`select owner_campaign_confirm_payment($1,'payment-1',1)`,[campaign]),/does not match/);
    await db.query(`select owner_campaign_confirm_payment($1,'payment-1',700)`,[campaign]);
    await db.query(`select owner_campaign_confirm_payment($1,'payment-1',700)`,[campaign]);
    await db.query(`select owner_campaign_review($1,true)`,[campaign]);
    await db.exec(`update owner_campaigns set starts_at=now()-interval '12 hours'`);
    assert.equal((await admit("view",{...area,city:"Milwaukee"})).rows[0].ok,false);
    assert.equal((await admit("view",area,undefined,owner)).rows[0].ok,false);
    assert.equal((await admit()).rows[0].ok,true);
    assert.equal((await admit()).rows[0].ok,true); // retry is idempotent
    assert.equal((await db.query(`select views,spent_cents from owner_campaigns`)).rows[0].views,1);
    assert.equal((await admit("click",area,undefined,stranger)).rows[0].ok,true);
    assert.equal((await admit("click",area,undefined,stranger)).rows[0].ok,true);
    assert.equal((await db.query(`select clicks from owner_campaigns`)).rows[0].clicks,1);
    assert.equal((await admit("view",area,"40000000-0000-0000-0000-000000000002")).rows[0].ok,true);
    assert.equal((await admit("view",area,"40000000-0000-0000-0000-000000000003")).rows[0].ok,false);
    assert.equal((await db.query(`select count(*)::int n from owner_campaign_candidates($1,$2,$3)`,[area,"b".repeat(64),stranger])).rows[0].n,1);
    assert.equal((await db.query(`select count(*)::int n from owner_campaign_candidates($1,$2,$3)`,[{...area,country:"Canada"},"b".repeat(64),stranger])).rows[0].n,0);
    const secondSalon='10000000-0000-0000-0000-000000000002', secondPost='20000000-0000-0000-0000-000000000002', secondCampaign='30000000-0000-0000-0000-000000000002';
    await db.exec(`insert into locations values('${secondSalon}','active','${salon}');insert into salon_settings values('${secondSalon}',true);
      insert into salon_profile_looks values('${secondPost}','${secondSalon}','Second salon','Another manicure','published','${stranger}',false,null);`);
    await db.query(`select owner_campaign_create($1,$2,$3,'salon_profile_look',$4,'city','Chicago','United States','Illinois','Chicago',500,7)`,[secondCampaign,secondSalon,stranger,secondPost]);
    await db.query(`select owner_campaign_confirm_payment($1,'payment-2',700)`,[secondCampaign]);await db.query(`select owner_campaign_review($1,true)`,[secondCampaign]);
    await db.exec(`update owner_campaigns set starts_at=now()-interval '12 hours'`);
    const competition=await db.query(`select id,salon_id from owner_campaign_candidates($1,$2,null)`,[area,'c'.repeat(64)]);
    assert.equal(competition.rows[0].id,secondCampaign);assert.equal(new Set(competition.rows.map(row=>row.salon_id)).size,2);
    await db.exec(`update owner_campaign_settings set config=jsonb_set(config,'{maxAdsPerDay}','3')`);
    const differentVisitor='d'.repeat(64);
    const globalAdmit=(id,nonce)=>db.query(`select owner_campaign_admit($1,$2,'view',$3,null,$4) ok`,[id,differentVisitor,area,nonce]);
    assert.equal((await globalAdmit(campaign,'60000000-0000-0000-0000-000000000001')).rows[0].ok,true);
    assert.equal((await globalAdmit(secondCampaign,'60000000-0000-0000-0000-000000000002')).rows[0].ok,true);
    assert.equal((await globalAdmit(secondCampaign,'60000000-0000-0000-0000-000000000003')).rows[0].ok,true);
    assert.equal((await globalAdmit(campaign,'60000000-0000-0000-0000-000000000004')).rows[0].ok,false);
    await db.exec(`insert into salon_profile_look_saves values('50000000-0000-0000-0000-000000000001','${stranger}','${post}');
      insert into salon_profile_comments values('50000000-0000-0000-0000-000000000002','${stranger}','${post}',null,null,'visible',false);
      insert into salon_profile_booking_requests values('50000000-0000-0000-0000-000000000003','${stranger}','${post}','requested');`);
    assert.equal((await db.query(`select bookings from owner_campaigns where id='${campaign}'`)).rows[0].bookings,0);
    await db.exec(`update salon_profile_booking_requests set status='approved'; update salon_profile_comments set status='visible';`);
    assert.deepEqual((await db.query(`select likes,comments,bookings from owner_campaigns where id='${campaign}'`)).rows[0],{likes:1,comments:1,bookings:1});
    await db.query(`select owner_campaign_change($1,$2,$3,'pause')`,[campaign,salon,owner]);
    assert.equal((await admit("view",area,"40000000-0000-0000-0000-000000000004")).rows[0].ok,false);
    await db.query(`select owner_campaign_change($1,$2,$3,'resume')`,[campaign,salon,owner]);
    await db.exec(`update salon_profile_looks set safety_hold=true`);
    assert.equal((await admit("view",area,"40000000-0000-0000-0000-000000000004")).rows[0].ok,false);
    assert.equal((await db.query(`select status from owner_campaigns where id='${campaign}'`)).rows[0].status,"paused");
    await db.query(`select owner_campaign_change($1,$2,$3,'cancel')`,[campaign,salon,owner]);
    await assert.rejects(db.query(`select owner_campaign_change($1,$2,$3,'resume')`,[campaign,salon,owner]),/cannot be changed/);
    await db.exec(`set role authenticated`);
    await assert.rejects(db.query(`select owner_campaign_confirm_payment($1,'hacked',700)`,[campaign]),/permission denied/);
    await assert.rejects(db.query(`select * from owner_campaigns`),/permission denied/);
  } finally { await db.close(); }
});
