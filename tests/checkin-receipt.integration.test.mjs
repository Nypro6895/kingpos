import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const salon = '00000000-0000-4000-8000-000000000001';
const other = '00000000-0000-4000-8000-000000000002';
const customer = '00000000-0000-4000-8000-000000000003';
const visit = '00000000-0000-4000-8000-000000000004';
const second = '00000000-0000-4000-8000-000000000005';
test('Receipt entitlement, daily queue, retry stability, scan isolation and completed visits', async () => {
 const db = new PGlite();
 try {
  await db.exec(`create role authenticated; create role anon; create role service_role bypassrls;
   create table locations(id uuid primary key,name text);
   create table users(id uuid primary key);
   create table customers(id uuid primary key,location_id uuid,name text,phone text);
   create table pos_live_drafts(id uuid primary key,salon_id uuid,token text,status text);
   create table customer_visits(id uuid primary key,salon_id uuid,customer_id uuid,checked_in_at timestamptz,status text,source text,appointment_id uuid,ticket_id uuid,origin_metadata jsonb);
   create function current_public_user_id() returns uuid language sql as $$select nullif(current_setting('test.user',true),'')::uuid$$;
   create function lifecycle_user_is_salon_owner(salon uuid,actor uuid,pending boolean) returns boolean language sql as $$select salon=actor$$;
   create function get_salon_business_timezone(salon uuid) returns text language sql as $$select 'America/Chicago'::text$$;
   create function customer_visit_requested_services_json(visit uuid) returns jsonb language sql as $$select '[]'::jsonb$$;
   insert into locations values('${salon}','Salon A'),('${other}','Salon B');
   insert into customers values('${customer}','${salon}','Customer',null);
   insert into pos_live_drafts values('${salon}','${salon}','paired','draft'),('${other}','${other}','other','draft');
   insert into customer_visits values('${visit}','${salon}','${customer}','2026-10-08T15:00:00Z','waiting','customer_screen',null,null,'{"token":"paired"}'),
    ('${second}','${salon}','${customer}','2026-10-08T16:00:00Z','waiting','customer_screen',null,null,'{"token":"paired"}');`);
  await db.exec(fs.readFileSync('supabase/migrations/202610080007_checkin_receipt_plugin.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610080008_checkin_receipt_billing_access.sql','utf8'));
  const issue = async (token='paired', id=visit) => (await db.query('select issue_checkin_receipt($1,$2) as receipt',[token,id])).rows[0].receipt;
  assert.equal(await issue(),null);
  await db.exec(`insert into checkin_receipt_subscriptions(salon_id,paid_until) values('${salon}',now()+interval '1 month')`);
  await db.exec('set role anon');
  const receipt = await issue();
  assert.equal(receipt.queueNumber,1);
  assert.equal(receipt.businessDate,'2026-10-08');
  assert.deepEqual(await issue(),receipt);
  assert.equal((await issue('paired',second)).queueNumber,2);
  const tomorrow='00000000-0000-4000-8000-000000000006';
  await db.exec('reset role');
  await db.exec(`insert into customer_visits values('${tomorrow}','${salon}','${customer}','2026-10-09T06:00:00Z','waiting','customer_screen',null,null,'{"token":"paired"}')`);
  await db.exec('set role anon');
  const nextDay=await issue('paired',tomorrow);
  assert.equal(nextDay.queueNumber,1);assert.equal(nextDay.businessDate,'2026-10-09');
  await assert.rejects(issue('other'), /no longer waiting/);
  await assert.rejects(issue('invalid'), /Invalid customer display/);
  await assert.rejects(db.query('select * from checkin_receipts'), /permission denied/);
  await assert.rejects(db.query('select resolve_checkin_receipt($1,$2)',[salon,visit]), /permission denied/);
  await db.exec('reset role');
  const resolve = async (scope=salon) => (await db.query('select resolve_checkin_receipt($1,$2) as visit',[scope,visit])).rows[0].visit;
  assert.equal((await resolve()).customerName,'Customer');
  assert.equal(await resolve(other),null);
  await db.exec(`update customer_visits set status='completed' where id='${visit}'`);
  assert.equal(await resolve(),null);
  await assert.rejects(issue(), /no longer waiting/);
  await db.exec(`update checkin_receipt_subscriptions set paid_until=now()-interval '1 day'`);
  assert.equal(await issue('paired',second),null);
  await db.exec(`set role authenticated; select set_config('test.user','${other}',false);`);
  assert.equal((await db.query('select * from checkin_receipt_subscriptions')).rows.length,0);
  await assert.rejects(db.exec(`insert into checkin_receipt_subscriptions(salon_id) values('${other}')`), /permission denied/);
  await db.exec('reset role; set role service_role');
  assert.equal((await db.query('select * from checkin_receipt_subscriptions')).rows.length,1);
  await db.query('update checkin_receipt_subscriptions set paid_until=now()+interval \'1 month\' where salon_id=$1',[salon]);
 } finally { await db.close(); }
});
